"""Shared Gecko pieces — true of Camoufox, stock Firefox and Tor Browser alike.

Camoufox layers its Windows spoofing on top of these; the non-spoofing engines
use them as they are. Everything here is engine-neutral: no fingerprint, no
``CAMOU_CONFIG``, no per-profile fontconfig. Those belong in the engine module.
"""

from __future__ import annotations

import json
from pathlib import Path

from kiwi_proxy import gateway

from .. import desktop, gpu, paths
from ..models import ContainerSpec, Profile

# The browser's profile directory, bind-mounted into every engine's container.
PROFILE_MOUNT = "/profile"

# Gateway loopback services, in the netns the browser shares with the gateway.
# kiwi-proxy's contract (docs/consumers.md): its forwarder and resolver.
FORWARDER_HOST, _port = gateway.FORWARDER.rsplit(":", 1)
FORWARDER_PORT = int(_port)
RESOLVER_HOST = gateway.RESOLVER


def accelerated(profile: Profile) -> bool:
    """Hardware rendering is wanted *and* this host can deliver it — by
    measurement where there is one, by plan otherwise (see core/gpu.py)."""
    return profile.gpu_accel and gpu.accelerated()


def is_dark(profile: Profile) -> bool | None:
    """Dark chrome and dark pages? None leaves the browser to its own default."""
    if profile.appearance == "host":
        return desktop.prefers_dark()
    return profile.appearance == "dark"


def network_prefs(profile: Profile, *, force_remote_dns: bool = False) -> dict[str, object]:
    """Send everything through the gateway forwarder and let nothing leak around it.

    These prefs are what makes the single permitted destination the *only* way
    out, so they hold for every Gecko engine. ``force_remote_dns`` is for Tor
    Browser, which must resolve at the exit (``.onion`` has no local answer)
    whatever the profile's DNS mode says.
    """
    remote_dns = True if force_remote_dns else profile.dns.mode == "remote"
    return {
        # Proxy: everything through the gateway's forwarder, never direct.
        "network.proxy.type": 1,
        "network.proxy.socks": FORWARDER_HOST,
        "network.proxy.socks_port": FORWARDER_PORT,
        "network.proxy.socks_version": 5,
        "network.proxy.socks_remote_dns": remote_dns,
        # Defaults to true, which permits a direct fallback. Never.
        "network.proxy.failover_direct": False,
        "network.proxy.allow_bypass": False,
        # The browser must not run its own DoH and bypass the gateway resolver.
        "network.trr.mode": 5,
        # No speculative traffic outside a user action.
        "network.dns.disablePrefetch": True,
        "network.prefetch-next": False,
        "network.predictor.enabled": False,
        "network.http.speculative-parallel-limit": 0,
        "browser.send_pings": False,
        "network.captive-portal-service.enabled": False,
    }


def user_js(prefs: dict[str, object]) -> str:
    """Render prefs as a Firefox user.js.

    user.js is re-applied on every startup and overrides prefs.js, so it is the
    right place for settings that must never drift.
    """
    lines = [
        "// generated by kiwi-fox — do not edit; rewritten on every launch",
    ]
    for key in sorted(prefs):
        # json.dumps gives exactly the literals Firefox wants: true/false for
        # booleans, bare numbers, and properly escaped quoted strings.
        lines.append(f"user_pref({json.dumps(key)}, {json.dumps(prefs[key])});")
    return "\n".join(lines) + "\n"


def base_spec(
    profile: Profile,
    *,
    image: str,
    gateway: str,
    engine_dir: Path,
    engine_mount: str,
    env: dict[str, str],
    extra_volumes: list[tuple[str, str, str]] | None = None,
) -> ContainerSpec:
    """The container every Gecko engine runs in: the gateway's netns, zero
    capabilities but ``SYS_CHROOT`` for the content sandbox, and the engine and
    profile mounts. Camoufox builds its own (it adds a per-profile fontconfig and
    CAMOU_CONFIG); the non-spoofing engines use this as-is."""
    pdir = paths.profile_dir(profile.id)
    plan = gpu.plan() if accelerated(profile) else None
    if plan:
        env = {**env, **plan.env}
    volumes = [
        # ",z" is shared relabelling: one engine copy serves every profile.
        (str(engine_dir), engine_mount, "ro,z"),
        (str(pdir / "browser-data"), PROFILE_MOUNT, "rw,z"),
        (str(pdir / "downloads"), "/downloads", "rw,z"),
        *(extra_volumes or []),
    ]
    return ContainerSpec(
        name=paths.browser_name(profile.id),
        image=image,
        network=f"container:{gateway}",
        env=env,
        volumes=volumes,
        devices=list(plan.devices) if plan else [],
        cap_drop=["all"],
        # Firefox's content sandbox chroots each content process; without the
        # capability its Chroot Helper segfaults and every tab dies. The real
        # boundary is the netns with no route — see docs/decisions.md.
        cap_add=["SYS_CHROOT"],
        security_opt=["no-new-privileges", "label=disable"],
        userns="keep-id",
        labels={"app": "kiwi-fox", "kiwi-fox.profile": profile.id},
    )
